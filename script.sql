    pet_id,
    vaccine_id,
    type,
    message,
    due_date,
    sent,
    created_at
)
SELECT
    v.pet_id,
    v.id,
    'VACCINE_OVERDUE',
    'Vacina ''' || v.name || ''' do pet ' || p.name ||
    ' está vencida. Regularize o quanto antes.',
    v.due_date,
    FALSE,
    CURRENT_TIMESTAMP
FROM vaccines v
         JOIN pets p ON p.id = v.pet_id
WHERE v.status = 'OVERDUE';

